import { z } from 'zod';

export const validators = {
  // Строгое имя (буквы, пробелы, дефисы)
  name: (min = 2, max = 50) =>
    z
      .string()
      .trim()
      .min(min, `Имя слишком короткое (минимум ${min} символа(-ов))`)
      .max(max, `Имя слишком длинное (максимум ${max} символов)`)
      .regex(/^[a-zA-Zа-яА-ЯёЁ\s-]+$/, 'Имя может содержать только буквы, пробелы и дефисы'),

  // Email
  email: () =>
    z
      .email('Неверный формат электронной почты'),

  // Телефон
  phone: () =>
    z
      .string()
      .trim()
      .regex(/^\+?[0-9\s\-()]{7,20}$/, 'Неверный формат номера телефона'),

  // Целое число (например, возраст или количество)
  integer: (min = 0, max = 150) =>
    z.coerce
      .number()
      .int('Значение должно быть целым числом')
      .min(min, `Минимальное значение: ${min}`)
      .max(max, `Максимальное значение: ${max}`),

  // 👈 Универсальный валидатор для массивов с выбором (чекбоксы / мультиселект)
  selection: <T extends string>(values: readonly T[], min = 1, max = values.length) =>
    z
      .array(z.enum(values as [T, ...T[]]))
      .min(min, `Выберите хотя бы ${min} вариант(-ов)`)
      .max(max, `Можно выбрать максимум ${max} вариант(-ов)`),
};